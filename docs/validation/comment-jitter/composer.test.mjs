const activity={meme_id:'meme',upvotes:1,downvotes:0,my_vote:0,comment_count:1};
const row={id:'comment',body:'Existing comment',author_label:'Delegate',created_at:'2026-11-14T09:00:00Z',is_own:false,can_remove:false};
test('typing keeps the input, draft, and composer controls stable across polls; drafts and collapse release layout guards correctly',async()=>{
 const fixture={activity,rows:[row],commentLoads:0,poll:null,loadActivity:async()=>activity};
 globalThis.__commentFixture={React,fixture};
 const {MemeDiscussion}=await import('data:text/javascript;base64,'+Buffer.from(prefix+output).toString('base64'));
 const editing=new Set();
 let renderer;
 await act(async()=>{renderer=create(React.createElement(MemeDiscussion,{meme:{id:'meme',activity},onActivity(){},onEditingChange(id,value){if(value)editing.add(id);else editing.delete(id);}}));});
 const toggle=()=>renderer.root.findAllByType('button').find(button=>button.props.accessibilityLabel?.startsWith('Comments,'));
 await act(async()=>toggle().props.onPress());
 const input=renderer.root.findByType('input');
 const buttons=renderer.root.findAllByType('button').length;
 await act(async()=>{input.props.onFocus();input.props.onChangeText('My draft');});
 assert.equal(editing.has('meme'),true);
 const loads=fixture.commentLoads;
 fixture.rows=[row,{...row,id:'new',body:'New arrival'}];
 await act(async()=>fixture.poll());
 assert.equal(fixture.commentLoads,loads,'No background thread replacement while composing');
 assert.equal(renderer.root.findByType('input'),input,'Input must not remount');
 assert.equal(input.props.value,'My draft');
 assert.equal(renderer.root.findAllByType('button').length,buttons,'Typing must not insert controls');
 await act(async()=>input.props.onBlur());
 assert.equal(editing.has('meme'),true,'Unsent draft keeps layout stable');
 await act(async()=>toggle().props.onPress());
 assert.equal(editing.size,0,'A closed thread cannot indefinitely pause the feed');
 await act(async()=>toggle().props.onPress());
 assert.equal(renderer.root.findByType('input').props.value,'My draft');
 assert.equal(editing.has('meme'),true);
 // A poll already in flight must also be ignored if focus changes before it resolves.
 await act(async()=>renderer.root.findAllByType('button').find(button=>button.findAllByType('text').some(text=>text.children.includes('Cancel'))).props.onPress());
 let resolveActivity;
 fixture.loadActivity=()=>new Promise(resolve=>{resolveActivity=resolve;});
 const inFlight=fixture.poll();
 await act(async()=>renderer.root.findByType('input').props.onFocus());
 const before=fixture.commentLoads;
 await act(async()=>{resolveActivity(activity);await inFlight;});
 assert.equal(fixture.commentLoads,before,'Late polls cannot replace the focused thread');
 await act(async()=>renderer.unmount());
 assert.equal(editing.size,0,'Unmount must release the gallery guard');
});

